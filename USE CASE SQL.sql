SELECT SEAT_NUM, NAME
     , ROW_NUMBER() OVER(ORDER BY SEAT_NUM) AS ROWNUM_SEATS
     , COUNT(1)     OVER()                  AS COUNT_SEATS
     , CASE WHEN MOD(ROWNUM_SEATS, 2) = 0   THEN ROWNUM_SEATS - 1  -- EVEN: MOVE UP
            WHEN ROWNUM_SEATS = COUNT_SEATS THEN ROWNUM_SEATS      -- LAST ODD: STAYS
            ELSE ROWNUM_SEATS + 1                                  -- ODD : MOVE DOWN 
       END  AS NEW_SEAT_ID
FROM   HRMS.BRNZ.STUDENTS ;